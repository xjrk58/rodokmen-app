#!/usr/bin/env bash
# Validates workspace.dsl and regenerates every diagram in generated/ from it:
#   generated/mermaid/*.mmd     Mermaid, exported by Structurizr (GitHub renders it)
#   generated/mermaid.md        the same diagrams as Mermaid blocks in one page
#   generated/plantuml/*.puml   C4-PlantUML, exported by Structurizr
#   generated/svg/*.svg         the C4-PlantUML diagrams rendered by PlantUML (status styles, legend)
#
# Needs only Docker. Usage: docs/architecture/generate.sh
# Set PNG_DIR to also render PNGs there, for looking at them. It must be outside the repo,
# because the repo guard refuses raster images outside app/.
set -euo pipefail

STRUCTURIZR_IMAGE=${STRUCTURIZR_IMAGE:-structurizr/structurizr:2026.10.26}
PLANTUML_IMAGE=${PLANTUML_IMAGE:-plantuml/plantuml:1.2026.9}

here=$(cd "$(dirname "$0")" && pwd)
cd "$here"
user="$(id -u):$(id -g)"

structurizr() {
  docker run --rm -u "$user" -v "$here":/usr/local/structurizr "$STRUCTURIZR_IMAGE" "$@"
}

plantuml() {
  docker run --rm -u "$user" -v "$here":/data -w /data "$PLANTUML_IMAGE" "$@"
}

echo "Validating workspace.dsl"
log=$(structurizr validate -w workspace.dsl 2>&1) || { echo "$log"; exit 1; }
if grep -q ' ERROR ' <<<"$log"; then echo "$log"; exit 1; fi

rm -rf generated
mkdir -p generated

echo "Exporting Mermaid and C4-PlantUML"
structurizr export -w workspace.dsl -f mermaid -o generated/mermaid >/dev/null
structurizr export -w workspace.dsl -f plantuml/c4plantuml -o generated/plantuml >/dev/null

# Structurizr names every file structurizr-<view key>; the view keys are already unique and
# ordered, so drop the prefix.
for f in generated/mermaid/structurizr-* generated/plantuml/structurizr-*; do
  mv "$f" "$(dirname "$f")/$(basename "$f" | sed 's/^structurizr-//')"
done

echo "Rendering SVG with PlantUML"
plantuml -tsvg -o /data/generated/svg generated/plantuml/*.puml

{
  echo "# Rodokmen C4 diagrams (Mermaid)"
  echo
  echo "Generated by \`docs/architecture/generate.sh\` from \`docs/architecture/workspace.dsl\`; do not edit."
  echo "Mermaid shows status by colour only: blue borders are Built, orange In progress, white boxes"
  echo "with grey text Planned. The SVGs in [svg/](svg/) also show dashed and dotted borders and a legend."
  for f in generated/mermaid/*.mmd; do
    name=$(basename "$f" .mmd)
    echo
    echo "## $name"
    echo
    echo '```mermaid'
    cat "$f"
    echo
    echo '```'
  done
} > generated/mermaid.md

if [ -n "${PNG_DIR:-}" ]; then
  mkdir -p "$PNG_DIR"
  png_dir=$(cd "$PNG_DIR" && pwd)
  case "$png_dir/" in "$(git -C "$here" rev-parse --show-toplevel)/"*)
    echo "PNG_DIR must be outside the repo (the repo guard refuses raster images)"; exit 1;;
  esac
  echo "Rendering PNG into $png_dir"
  docker run --rm -u "$user" -v "$here":/data -v "$png_dir":/png -w /data "$PLANTUML_IMAGE" \
    -tpng -o /png generated/plantuml/*.puml
fi

echo "Done: $(find generated/svg -name '*.svg' | wc -l) diagrams in docs/architecture/generated/"
